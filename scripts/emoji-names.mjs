// Writes src/emoji-names.ts: the search words of the picker's emojis, English and Italian, from CLDR annotations.
// node scripts/emoji-names.mjs <cldr-json>/cldr-annotations-full/annotations  (github.com/unicode-org/cldr-json)
import { readFileSync, writeFileSync } from 'node:fs'

const dir = process.argv[2]
const cldr = (l) => JSON.parse(readFileSync(`${dir}/${l}/annotations.json`, 'utf8')).annotations.annotations
const langs = [cldr('en'), cldr('it')]
const picker = readFileSync(new URL('../src/components/EmojiPicker.tsx', import.meta.url), 'utf8')
const emojis = [...picker.matchAll(/emojis:\s*'([^']+)'/g)].flatMap((m) => m[1].split(' '))
const codes = readFileSync(new URL('../src/shortcodes-table.ts', import.meta.url), 'utf8')
const names = {}
for (const [, code, e] of codes.matchAll(/"([^"]+)": "([^"]+)"/g)) (names[e] ??= []).push(code.replace(/_/g, ' '))

const lines = emojis.map((e) => {
  const a = langs.map((l) => l[e] ?? l[e.replace(/️/g, '')])
  const words = [...new Set([...a.flatMap((x) => [...(x?.tts ?? []), ...(x?.default ?? [])]), ...(names[e] ?? [])].map((w) => w.toLowerCase()))]
  return `  ${JSON.stringify(e)}: ${JSON.stringify(words.join('|'))},`
})
writeFileSync(
  new URL('../src/emoji-names.ts', import.meta.url),
  `// Generated by scripts/emoji-names.mjs from CLDR annotations (en, it): the words each picker emoji is found by.\nconst names: Record<string, string> = {\n${lines.join('\n')}\n}\nexport default names\n`,
)
console.log(emojis.length, 'emojis')
